#!/usr/bin/env python3
import json
import os
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

import send_scheduled_digest as digest  # noqa: E402

_original_generate = digest.generate_ai_report


def generate_via_vercel(selected, attention, days):
    run_id = os.getenv("GITHUB_RUN_ID", "").strip()
    sha = os.getenv("GITHUB_SHA", "").strip()
    workflow_token = os.getenv("GITHUB_WORKFLOW_TOKEN", "").strip()
    base_url = os.getenv("PUBLIC_BASE_URL", "https://ntue-news-bulletin.vercel.app").rstrip("/")
    if not run_id or not sha or not workflow_token:
        return _original_generate(selected, attention, days)

    items = [
        {
            "title": item.get("title"),
            "source": item.get("source"),
            "publisher": item.get("publisher"),
            "publish_time": item.get("publish_time"),
            "risk_score": digest.risk_score(item),
        }
        for item in selected[:120]
    ]
    if not items:
        return _original_generate(selected, attention, days)

    payload = json.dumps({"days": days, "items": items}, ensure_ascii=False).encode("utf-8")
    req = urllib.request.Request(
        f"{base_url}/api/ai-report/scheduled",
        data=payload,
        headers={
            "Content-Type": "application/json",
            "Accept": "application/json",
            "x-github-run-id": run_id,
            "x-github-sha": sha,
            "x-github-workflow-token": workflow_token,
            "User-Agent": "NTUE-GitHub-Actions-Scheduled-Report/2.0",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=55) as resp:
            data = json.loads(resp.read().decode("utf-8"))
        report = data.get("report")
        if not isinstance(report, dict):
            raise ValueError("scheduled endpoint returned no report")
        required = ["overall", "immediate_action", "themes", "risk_assessment", "recommendations", "watchlist"]
        if not all(key in report for key in required):
            raise ValueError("scheduled endpoint report schema incomplete")
        print(f"[digest] AI report generated by Vercel endpoint; run={run_id}")
        return report, True
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="ignore")
        print(f"[digest] scheduled AI endpoint HTTP {exc.code}: {detail[:800]}")
    except Exception as exc:
        print(f"[digest] scheduled AI endpoint failed: {exc}")
    return _original_generate(selected, attention, days)


def submit_with_requests(recipient, subject, body_fields, source_url, pdf_path):
    import requests

    endpoint = f"https://formsubmit.co/{urllib.parse.quote(recipient, safe='@.+-_')}"
    fields = {
        "_subject": subject,
        "_template": "box",
        "_captcha": "false",
        "_url": source_url,
        **body_fields,
    }
    pdf = Path(pdf_path)
    try:
        with pdf.open("rb") as fh:
            response = requests.post(
                endpoint,
                data=fields,
                files={"attachment": (pdf.name, fh, "application/pdf")},
                headers={
                    "Origin": "https://ntue-news-bulletin.vercel.app",
                    "Referer": source_url,
                    "User-Agent": "Mozilla/5.0 NTUE-Opinion-Monitor/4.0",
                },
                timeout=45,
                allow_redirects=True,
            )
        lower = response.text.lower()
        success = response.ok and "unable to submit" not in lower and "error" not in lower
        print(
            f"[digest] FormSubmit requests upload HTTP {response.status_code} for {recipient}; "
            f"attachment={pdf.stat().st_size}B multipart={'multipart/form-data' in response.request.headers.get('Content-Type','')}"
        )
        return success
    except Exception as exc:
        print(f"[digest] FormSubmit requests upload failed for {recipient}: {exc}")
        return False


digest.generate_ai_report = generate_via_vercel
digest.submit_to_formsubmit = submit_with_requests

if __name__ == "__main__":
    digest.main()
